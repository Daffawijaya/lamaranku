const messages = appMessages as Record<string, Partial<Record<SettingsLanguage, string>>>;
const normalizedMessages = new Map(Object.entries(messages).map(([key, value]) => [key.toLocaleLowerCase(), value]));
const templateMessages = Object.entries(messages).filter(([key]) => /\{\d+\}/.test(key)).sort(([a], [b]) => b.replace(/\{\d+\}/g, "").length - a.replace(/\{\d+\}/g, "").length).map(([key, entry]) => {
  const indexes = [...key.matchAll(/\{(\d+)\}/g)].map(match => Number(match[1]));
  const escape = (part: string) => part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  return { entry, indexes, pattern: new RegExp("^" + key.split(/\{\d+\}/).map(escape).join("(.*?)") + "$", "i") };
});
export function settingsTranslator(language: SettingsLanguage) {
  const translate = (text: string): string => {
    const decoded = text.replaceAll("&amp;", "&").replaceAll("&copy;", "©").replaceAll("&quot;", '"').replaceAll("&#39;", "'");
    const entry = messages[text] ?? messages[decoded] ?? normalizedMessages.get(decoded.toLocaleLowerCase());
    if (entry) return language === "id" ? entry.id ?? decoded : TRANSLATIONS[language][text] ?? entry[language] ?? entry.en ?? decoded;
    if (language !== "id" && TRANSLATIONS[language][text]) return TRANSLATIONS[language][text];
    for (const template of templateMessages) {
      const match = template.pattern.exec(decoded);
      if (!match) continue;
      const translated = language === "id" ? template.entry.id : template.entry[language] ?? template.entry.en;
      if (!translated) return decoded;
      const values: Record<number, string> = {};
      template.indexes.forEach((index, i) => { values[index] = translate(match[i + 1]); });
      return translated.replace(/\{(\d+)\}/g, (_, index) => values[Number(index)] ?? "");
    }
    return language === "id" ? decoded : TRANSLATIONS.en[text] ?? decoded;
  };
  return translate;
}
